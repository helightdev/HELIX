using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Helix.Weave.Lowering;

/// <summary>
/// Relocates mixin declarations and generates the wiring around them.
///
/// The relocated class keeps its own name and namespace, so weave-method signatures and bodies
/// are moved verbatim — nothing inside a body is ever read or rewritten. What changes is the
/// declaration: the Attribute base goes away, a decoder is added, and a nested Mixin class is
/// generated to call the weave methods.
/// </summary>
public static class LoweringEmitter {
  public const string MixinTypeName = "__Mixin";

  public static string EmitMixin(MixinDeclaration declaration) {
    var builder = new StringBuilder();
    builder.AppendLine("// <auto-generated/> relocated by Helix.Weave.Lower");
    builder.AppendLine("#nullable disable");
    builder.AppendLine("using Helix.Weave;");
    builder.AppendLine("using Microsoft.CodeAnalysis;");
    foreach (var directive in UsingsOf(declaration)) builder.AppendLine(directive);
    builder.AppendLine();

    var indent = "";
    if (declaration.Namespace is not null) {
      builder.AppendLine($"namespace {declaration.Namespace} {{");
      indent = "  ";
    }

    builder.AppendLine($"{indent}public sealed partial class {declaration.Name} {{");
    foreach (var member in declaration.RelocatedMembers)
      builder.AppendLine(Relocate(member, indent + "  "));
    foreach (var method in declaration.Methods)
      builder.AppendLine(Relocate(method.Syntax, indent + "  ", stripWeaveAttributes: true));

    EmitDecoder(builder, declaration, indent + "  ");
    EmitMixinClass(builder, declaration, indent + "  ");
    builder.AppendLine($"{indent}}}");

    if (declaration.Namespace is not null) builder.AppendLine("}");
    return builder.ToString();
  }

  private static IEnumerable<string> UsingsOf(MixinDeclaration declaration) {
    // Seeded with what the file header already emits, so a mixin that imports the same
    // namespaces does not produce duplicate-using warnings.
    var seen = new HashSet<string>(System.StringComparer.Ordinal) {
      "using Helix.Weave;",
      "using Microsoft.CodeAnalysis;",
    };
    foreach (var directive in declaration.Syntax.SyntaxTree.GetRoot().DescendantNodes()
               .OfType<UsingDirectiveSyntax>()) {
      var text = directive.ToString().Trim();
      if (seen.Add(text)) yield return text;
    }
  }

  private static void EmitDecoder(StringBuilder builder, MixinDeclaration declaration, string indent) {
    builder.AppendLine();
    builder.AppendLine($"{indent}/// <summary>Decodes <c>{declaration.AttributeMetadataName}</c>'s arguments.</summary>");
    builder.AppendLine($"{indent}public static {declaration.Name} Decode(AttributeData data, SymbolFacts facts) {{");
    builder.AppendLine($"{indent}  var defaults = new {declaration.Name}();");
    builder.AppendLine($"{indent}  if (data is null) return defaults;");

    // Locals seeded from the defaults keep property initializers meaningful; the single object
    // initializer at the end is what makes `init` accessors work.
    foreach (var member in declaration.Decodable)
      builder.AppendLine($"{indent}  var {Local(member)} = defaults.{member.Name};");

    // Attributes can declare several constructors, so positional arguments are matched by the
    // parameter names of the constructor the application actually invoked, not by a guess.
    if (declaration.Decodable.Count > 0) {
      builder.AppendLine($"{indent}  var positional = data.ConstructorArguments;");
      builder.AppendLine($"{indent}  var parameters = data.AttributeConstructor?.Parameters ?? " +
                         "default(System.Collections.Immutable.ImmutableArray<IParameterSymbol>);");
      builder.AppendLine($"{indent}  for (var i = 0; i < positional.Length && i < parameters.Length; i++) {{");
      builder.AppendLine($"{indent}    var name = parameters[i].Name;");
      var first = true;
      foreach (var member in declaration.Decodable) {
        // Case-insensitive: the attribute being mirrored may name its parameters in camelCase.
        builder.AppendLine($"{indent}    {(first ? "if" : "else if")} " +
                           $"(string.Equals(name, \"{member.Name}\", System.StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine($"{indent}      {Local(member)} = {Convert("positional[i]", TypeOf(member))};");
        first = false;
      }
      builder.AppendLine($"{indent}  }}");
    }

    if (declaration.Decodable.Count > 0) {
      builder.AppendLine($"{indent}  foreach (var named in data.NamedArguments) {{");
      var firstNamed = true;
      foreach (var member in declaration.Decodable) {
        builder.AppendLine($"{indent}    {(firstNamed ? "if" : "else if")} " +
                           $"(string.Equals(named.Key, \"{member.Name}\", System.StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine($"{indent}      {Local(member)} = {Convert("named.Value", TypeOf(member))};");
        firstNamed = false;
      }
      builder.AppendLine($"{indent}  }}");
    }

    if (declaration.Decodable.Count == 0) {
      builder.AppendLine($"{indent}  return defaults;");
    } else {
      builder.AppendLine($"{indent}  return new {declaration.Name} {{");
      foreach (var member in declaration.Decodable)
        builder.AppendLine($"{indent}    {member.Name} = {Local(member)},");
      builder.AppendLine($"{indent}  }};");
    }
    builder.AppendLine($"{indent}}}");
  }

  private static string Local(ISymbol member) => "__" + member.Name;

  private static ITypeSymbol TypeOf(ISymbol member) => member switch {
    IPropertySymbol property => property.Type,
    IFieldSymbol field => field.Type,
    _ => null,
  };

  /// <summary>Reads one decoded attribute argument into its declared property type.</summary>
  private static string Convert(string access, ITypeSymbol type) {
    var name = type.ToDisplayString();
    var nullable = name.EndsWith("?", System.StringComparison.Ordinal);
    var bare = nullable ? name.Substring(0, name.Length - 1) : name;
    var underlyingEnum = type is INamedTypeSymbol { TypeArguments.Length: 1 } wrapper &&
                         wrapper.TypeArguments[0].TypeKind == TypeKind.Enum
      ? wrapper.TypeArguments[0]
      : type.TypeKind == TypeKind.Enum ? type : null;

    if (bare is "Helix.Weave.Literal") return $"Literal.From({access})";
    if (bare is "Helix.Weave.TypeRef") return $"facts.Ref({access}.Value as ITypeSymbol)";
    if (bare is "Helix.Weave.PureTypeRef")
      return $"facts.Detach(({access}.Kind == TypedConstantKind.Array " +
             $"? ({access}.Values.Length > 0 ? {access}.Values[0].Value : null) " +
             $": {access}.Value) as ITypeSymbol)";
    if (underlyingEnum is not null)
      return $"{access}.IsNull ? default : ({name})System.Convert.ToInt32({access}.Value)";
    if (type is IArrayTypeSymbol array) {
      // A null array constant has no Values at all, and an omitted optional argument still
      // arrives as a positional entry.
      var element = array.ElementType.ToDisplayString();
      var select = element switch {
        "Helix.Weave.TypeRef" => "facts.Ref(v.Value as ITypeSymbol)",
        "Helix.Weave.PureTypeRef" => "facts.Detach(v.Value as ITypeSymbol)",
        _ => $"({element})v.Value",
      };
      return $"{access}.IsNull ? null : {access}.Values.Select(v => {select}).ToArray()";
    }
    if (bare is "string") return $"(string){access}.Value";
    if (type.IsValueType && nullable)
      return $"{access}.IsNull ? default({name}) : ({bare}){access}.Value";
    return $"({name}){access}.Value";
  }

  private static void EmitMixinClass(StringBuilder builder, MixinDeclaration declaration, string indent) {
    var single = declaration.Methods.FirstOrDefault(m => m.Pass == WeavePass.Single);
    var prelude = declaration.Methods.FirstOrDefault(m => m.Pass == WeavePass.Prelude);
    var late = declaration.Methods.FirstOrDefault(m => m.Pass == WeavePass.Late);
    var entry = single ?? prelude;
    var targetType = entry?.TargetParameterType ?? "Helix.Weave.SymbolTarget";
    var carryType = prelude?.Carry?.ToDisplayString();

    builder.AppendLine();
    builder.AppendLine($"{indent}/// <summary>Generated dispatch for this mixin.</summary>");
    builder.AppendLine($"{indent}public sealed class {MixinTypeName} : Mixin {{");
    builder.AppendLine($"{indent}  public override string AttributeName => \"{declaration.AttributeMetadataName}\";");
    builder.AppendLine($"{indent}  public override Unit Unit => Unit.{declaration.Unit};");
    if (declaration.Order != 0) builder.AppendLine($"{indent}  public override int Order => {declaration.Order};");

    if (declaration.Unit == Unit.Derivation) {
      EmitDerivationDispatch(builder, declaration, indent, entry);
      builder.AppendLine($"{indent}}}");
      return;
    }

    if (late is not null) builder.AppendLine($"{indent}  public override bool HasLate => true;");
    builder.AppendLine();
    builder.AppendLine($"{indent}  public override object Prelude(SymbolTarget target, AttributeData attribute) {{");
    builder.AppendLine($"{indent}    if (target is not {targetType} typed) return null;");
    builder.AppendLine($"{indent}    var args = {declaration.Name}.Decode(attribute, target.Facts);");
    // Qualified: the generated override may share a name with the weave method it calls.
    var self = declaration.Name;
    if (carryType is null) {
      builder.AppendLine($"{indent}    {self}.{entry?.Symbol?.Name}(typed, args);");
      builder.AppendLine($"{indent}    return null;");
    } else {
      builder.AppendLine($"{indent}    return {self}.{entry?.Symbol?.Name}(typed, args);");
    }
    builder.AppendLine($"{indent}  }}");

    if (late is not null) {
      builder.AppendLine();
      builder.AppendLine($"{indent}  public override void Late(LateTarget target, object carry) =>");
      builder.AppendLine($"{indent}    {declaration.Name}.{late.Symbol?.Name}(target, ({carryType})carry);");
    }

    builder.AppendLine($"{indent}}}");
  }

  /// <summary>
  /// A derivation step is never triggered by the attribute pipeline; it is called with the
  /// property built so far and returns the next one.
  /// </summary>
  private static void EmitDerivationDispatch(StringBuilder builder, MixinDeclaration declaration,
                                             string indent, WeaveMethod entry) {
    builder.AppendLine();
    builder.AppendLine($"{indent}  public override object Prelude(SymbolTarget target, AttributeData attribute) => null;");
    builder.AppendLine();
    builder.AppendLine($"{indent}  public override DerivedProperty Derive(DerivationTarget target,");
    builder.AppendLine($"{indent}                                        AttributeData attribute,");
    builder.AppendLine($"{indent}                                        DerivedProperty property) {{");
    builder.AppendLine($"{indent}    var args = {declaration.Name}.Decode(attribute, target.Facts);");
    builder.AppendLine($"{indent}    return {declaration.Name}.{entry?.Symbol?.Name}(target, args, property);");
    builder.AppendLine($"{indent}  }}");
  }

  /// <summary>
  /// Moves a declaration verbatim, with a #line directive pointing back at the authoring source
  /// so compile errors land on the line the author wrote.
  /// </summary>
  private static string Relocate(MemberDeclarationSyntax member, string indent, bool stripWeaveAttributes = false) {
    var node = StripReadonly(stripWeaveAttributes ? StripWeaveAttributes(member) : member);
    var line = member.SyntaxTree.GetLineSpan(member.Span).StartLinePosition.Line + 1;
    var path = member.SyntaxTree.FilePath;

    var builder = new StringBuilder();
    if (!string.IsNullOrEmpty(path)) builder.AppendLine($"#line {line} \"{path.Replace("\\", "\\\\")}\"");
    foreach (var text in node.ToString().Replace("\r\n", "\n").Split('\n'))
      builder.AppendLine(text.Length == 0 ? "" : indent + text);
    if (!string.IsNullOrEmpty(path)) builder.AppendLine("#line default");
    return builder.ToString().TrimEnd('\n');
  }

  /// <summary>
  /// The relocated class is a data holder, not the attribute itself, so a decodable field cannot
  /// stay readonly — the generated decoder assigns it.
  /// </summary>
  private static MemberDeclarationSyntax StripReadonly(MemberDeclarationSyntax member) {
    if (member is not FieldDeclarationSyntax field) return member;
    var kept = field.Modifiers.Where(modifier => !modifier.IsKind(SyntaxKind.ReadOnlyKeyword));
    return field.WithModifiers(SyntaxFactory.TokenList(kept));
  }

  private static MemberDeclarationSyntax StripWeaveAttributes(MemberDeclarationSyntax member) {
    if (member is not MethodDeclarationSyntax method) return member;
    var kept = method.AttributeLists.Where(list => !list.Attributes.Any(attribute => {
      var name = attribute.Name.ToString();
      return name is "Weave" or "Prelude" or "Late"
          or "WeaveAttribute" or "PreludeAttribute" or "LateAttribute";
    }));
    return method.WithAttributeLists(SyntaxFactory.List(kept)).WithLeadingTrivia(SyntaxFactory.TriviaList());
  }

  /// <summary>
  /// Everything else in a mixin file: enums, helper classes, shared statics. A mixin file is
  /// lowered as a whole file — the [Mixin] classes get wiring, the rest travels verbatim.
  /// </summary>
  public static string EmitCompanions(SyntaxTree tree, IReadOnlyCollection<string> mixinTypeNames) {
    var root = tree.GetRoot();
    var removals = root.DescendantNodes()
      .OfType<ClassDeclarationSyntax>()
      .Where(node => mixinTypeNames.Contains(QualifiedNameOf(node)))
      .ToList();

    if (removals.Count == 0) return tree.ToString();

    var stripped = root.RemoveNodes(removals, SyntaxRemoveOptions.KeepNoTrivia);
    if (stripped is null) return null;

    // Nothing but the mixins lived here.
    var remaining = stripped.DescendantNodes().OfType<MemberDeclarationSyntax>()
      .Any(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax);
    return remaining ? stripped.ToFullString() : null;
  }

  /// <summary>Namespace-qualified name of a declaration, as discovery records it.</summary>
  public static string QualifiedNameOf(ClassDeclarationSyntax syntax) {
    var name = syntax.Identifier.Text;
    for (var parent = syntax.Parent; parent is not null; parent = parent.Parent) {
      switch (parent) {
        case NamespaceDeclarationSyntax ns: name = ns.Name + "." + name; break;
        case FileScopedNamespaceDeclarationSyntax file: name = file.Name + "." + name; break;
        case TypeDeclarationSyntax type: name = type.Identifier.Text + "." + name; break;
      }
    }
    return name;
  }

  /// <summary>The registry and generator entry point — the part that cannot be hand-maintained.</summary>
  public static string EmitRegistry(IReadOnlyList<MixinDeclaration> declarations) {
    var builder = new StringBuilder();
    builder.AppendLine("// <auto-generated/> generated by Helix.Weave.Lower");
    builder.AppendLine("#nullable disable");
    builder.AppendLine("using System.Collections.Generic;");
    builder.AppendLine("using Helix.Weave;");
    builder.AppendLine();
    builder.AppendLine("namespace Helix.Weave.Generated {");
    builder.AppendLine("  public sealed class MixinRegistry : IMixinRegistry {");
    builder.AppendLine("    public static readonly MixinRegistry Instance = new MixinRegistry();");
    builder.AppendLine("    private static readonly Mixin[] All = {");
    foreach (var declaration in declarations)
      builder.AppendLine($"      new {QualifiedMixin(declaration)}(),");
    builder.AppendLine("    };");
    builder.AppendLine("    public IReadOnlyList<Mixin> Mixins => All;");
    builder.AppendLine("  }");
    builder.AppendLine();
    builder.AppendLine("  [Microsoft.CodeAnalysis.Generator]");
    builder.AppendLine("  public sealed class WeaveGenerator : WeaveGeneratorBase {");
    builder.AppendLine("    protected override IReadOnlyList<Mixin> Mixins => MixinRegistry.Instance.Mixins;");
    builder.AppendLine("  }");
    builder.AppendLine("}");
    return builder.ToString();
  }

  public static string QualifiedMixin(MixinDeclaration declaration) =>
    (declaration.Namespace is null ? "" : "global::" + declaration.Namespace + ".") +
    declaration.Name + "." + MixinTypeName;
}
