using System;
using System.Collections.Generic;
using System.Linq;

namespace Helix.Weave;

/// <summary>
/// Turns a merged type into one generated source file. Works from value data only — no symbols,
/// no compilation — so it sits entirely behind the incremental pipeline's cache.
/// </summary>
public static class Renderer {
  public static string Render(MergedType merged) {
    var type = merged.Type;
    var usings = Distinct(merged.Emissions, EmissionTarget.Using);
    var annotations = Distinct(merged.Emissions, EmissionTarget.Annotation);
    var extends = Distinct(merged.Emissions, EmissionTarget.Extends);
    var implements = Distinct(merged.Emissions, EmissionTarget.Implements);
    var members = Ordered(merged.Emissions, EmissionTarget.Class);
    var files = Ordered(merged.Emissions, EmissionTarget.File);

    var builder = new SourceBuilder();
    builder.Line("// <auto-generated/>");
    builder.Line("#nullable disable");
    foreach (var item in usings) builder.Line("using " + item.TrimEnd(';') + ";");
    if (usings.Count > 0) builder.Line();

    var scope = string.IsNullOrEmpty(type.Namespace) ? null : builder.Braces("namespace " + type.Namespace);

    foreach (var annotation in annotations) builder.Line("[" + annotation.Trim('[', ']') + "]");

    var bases = new List<string>(extends);
    bases.AddRange(implements);
    var declaration = type.Keyword + " " + type.Name + type.TypeParameters +
                      (bases.Count == 0 ? "" : " : " + string.Join(", ", bases));

    using (builder.Braces(declaration)) {
      foreach (var member in members) { builder.Block(member); builder.Line(); }
      foreach (var method in BuildMethods(merged)) { builder.Block(method); builder.Line(); }
    }

    // File-level declarations land outside the namespace, which is where companion classes and
    // their extension methods have always been: user code picks them up without a using.
    scope?.Dispose();
    foreach (var file in files) { builder.Line(); builder.Block(file); }
    return builder.ToString();
  }

  /// <summary>
  /// Builds the methods injection contributions are woven into. Ordering is by priority, then by
  /// insertion sequence — the tie-break is part of the contract, not an accident.
  /// </summary>
  private static IReadOnlyList<string> BuildMethods(MergedType merged) {
    var grouped = new Dictionary<string, List<Emission>>(StringComparer.Ordinal);
    foreach (var emission in merged.Emissions) {
      if (emission.Target != EmissionTarget.Injection || emission.InjectionTarget is null) continue;
      if (!grouped.TryGetValue(emission.InjectionTarget, out var list))
        grouped.Add(emission.InjectionTarget, list = new List<Emission>());
      list.Add(emission);
    }

    var methods = new List<string>();
    foreach (var name in grouped.Keys.OrderBy(key => key, StringComparer.Ordinal)) {
      var contributions = grouped[name];
      contributions.Sort(static (left, right) => {
        var compared = left.Priority.CompareTo(right.Priority);
        return compared != 0 ? compared : left.Sequence.CompareTo(right.Sequence);
      });

      var resolved = merged.Targets.FirstOrDefault(
        target => string.Equals(target.Name, name, StringComparison.Ordinal));
      var declaration = resolved.Declaration ?? "private void " + name + "()";

      var builder = new SourceBuilder();
      using (builder.Braces(declaration)) {
        if (resolved.BaseCall is not null) builder.Line(resolved.BaseCall);
        foreach (var contribution in contributions) builder.Block(EnsureTerminated(contribution.Text));
      }
      methods.Add(builder.ToString().TrimEnd('\n'));
    }
    return methods;
  }

  /// <summary>
  /// Adds the semicolon a bare expression needs. Contributions are often deliberate fragments —
  /// a lone `try {`, a comment, a label — so only terminate what actually looks unterminated.
  /// </summary>
  private static string EnsureTerminated(string statement) {
    var trimmed = statement.TrimEnd();
    if (trimmed.Length == 0) return trimmed;

    var lastLine = trimmed.Substring(trimmed.LastIndexOf('\n') + 1).Trim();
    if (lastLine.StartsWith("//", StringComparison.Ordinal)) return trimmed;

    var last = trimmed[trimmed.Length - 1];
    return last is ';' or '}' or '{' or ':' ? trimmed : trimmed + ";";
  }

  private static List<string> Distinct(IReadOnlyList<Emission> emissions, EmissionTarget target) {
    var seen = new HashSet<string>(StringComparer.Ordinal);
    var result = new List<string>();
    foreach (var emission in emissions)
      if (emission.Target == target && !string.IsNullOrWhiteSpace(emission.Text) && seen.Add(emission.Text))
        result.Add(emission.Text);
    return result;
  }

  private static List<string> Ordered(IReadOnlyList<Emission> emissions, EmissionTarget target) {
    var result = new List<string>();
    foreach (var emission in emissions)
      if (emission.Target == target) result.Add(emission.Text);
    return result;
  }
}
