using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;

namespace Helix.Weave;

/// <summary>Turns a session's accumulated emissions into one generated source file.</summary>
public static class Renderer {
  public static string Render(WeaveSession session) {
    var pool = session.Pool;
    var outputs = session.Outputs.Outputs;
    var type = session.Type;

    var usings = Distinct(outputs, EmissionTarget.Using, pool);
    var annotations = Distinct(outputs, EmissionTarget.Annotation, pool);
    var extends = Distinct(outputs, EmissionTarget.Extends, pool);
    var implements = Distinct(outputs, EmissionTarget.Implements, pool);
    var members = Ordered(outputs, EmissionTarget.Class, pool);
    var files = Ordered(outputs, EmissionTarget.File, pool);

    var builder = new SourceBuilder();
    builder.Line("// <auto-generated/>");
    builder.Line("#nullable disable");
    foreach (var item in usings) builder.Line("using " + item.TrimEnd(';') + ";");
    if (usings.Count > 0) builder.Line();

    var namespaceName = type.ContainingNamespace is { IsGlobalNamespace: false } ns
      ? ns.ToDisplayString()
      : null;

    var scope = namespaceName is null ? null : builder.Braces("namespace " + namespaceName);

    foreach (var annotation in annotations) builder.Line("[" + annotation.Trim('[', ']') + "]");

    var bases = new List<string>();
    bases.AddRange(extends);
    bases.AddRange(implements);
    var declaration = DeclarationOf(type) + (bases.Count == 0 ? "" : " : " + string.Join(", ", bases));

    using (builder.Braces(declaration)) {
      foreach (var member in members) { builder.Block(member); builder.Line(); }
      foreach (var method in Weaver.BuildMethods(session)) { builder.Block(method); builder.Line(); }
    }

    // File-level declarations land outside the namespace, which is where companion classes and
    // their extension methods have always been: user code picks them up without a using.
    scope?.Dispose();
    foreach (var file in files) { builder.Line(); builder.Block(file); }
    return builder.ToString();
  }

  private static string DeclarationOf(INamedTypeSymbol type) {
    var kind = type.TypeKind switch {
      TypeKind.Struct => type.IsRecord ? "partial record struct" : "partial struct",
      TypeKind.Interface => "partial interface",
      _ => type.IsRecord ? "partial record" : "partial class",
    };
    var parameters = type.TypeParameters.Length == 0
      ? ""
      : "<" + string.Join(", ", type.TypeParameters.Select(p => p.Name)) + ">";
    // No accessibility modifier: a partial declaration inherits it, and guessing wrong is a
    // compile error on every internal or nested type.
    return kind + " " + type.Name + parameters;
  }

  private static List<string> Distinct(IReadOnlyList<MixinOutput> outputs, EmissionTarget target, StringPool pool) {
    var seen = new HashSet<string>(System.StringComparer.Ordinal);
    var result = new List<string>();
    foreach (var output in outputs) {
      if (output.Target != target) continue;
      var text = pool.Resolve(output.Text);
      if (!string.IsNullOrWhiteSpace(text) && seen.Add(text)) result.Add(text);
    }
    return result;
  }

  private static List<string> Ordered(IReadOnlyList<MixinOutput> outputs, EmissionTarget target, StringPool pool) {
    var result = new List<string>();
    foreach (var output in outputs)
      if (output.Target == target) result.Add(pool.Resolve(output.Text));
    return result;
  }
}
